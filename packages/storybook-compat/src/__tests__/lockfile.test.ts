import { describe, expect, it } from "vitest";

import { diffLockfile, isSupportedLockfile } from "../lockfile";
import { readPackageNames } from "../moduleGraph";

const yarnBerry = (
  electron: string,
  react = "18.3.1",
) => `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"@types/react@npm:^18.0.0":
  version: 18.3.3
  resolution: "@types/react@npm:18.3.3"
  checksum: 10c0/aaa
  languageName: node
  linkType: hard

"electron@npm:^30.0.0, electron@npm:^30.1.0":
  version: ${electron}
  resolution: "electron@npm:${electron}"
  checksum: 10c0/${electron}
  languageName: node
  linkType: hard

"react@npm:^18.0.0":
  version: ${react}
  resolution: "react@npm:${react}"
  checksum: 10c0/${react}
  languageName: node
  linkType: hard

"@acme/ui@workspace:packages/ui":
  version: 0.0.0-use.local
  resolution: "@acme/ui@workspace:packages/ui"
  dependencies:
    react: "npm:^18.0.0"
  languageName: unknown
  linkType: soft
`;

const yarnV1 = (react: string) => `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/runtime@^7.0.0":
  version "7.24.0"
  resolved "https://registry.yarnpkg.com/@babel/runtime/-/runtime-7.24.0.tgz#abc"
  integrity sha512-abc

react@^18.0.0, react@^18.2.0:
  version "${react}"
  resolved "https://registry.yarnpkg.com/react/-/react-${react}.tgz#def"
  integrity sha512-${react}
`;

const pnpmLock = (undici: string, peer = "18.3.1") => `lockfileVersion: '9.0'

importers:

  .:
    devDependencies:
      undici:
        specifier: ^6.0.0
        version: ${undici}

packages:

  '@testing-library/react@16.0.0':
    resolution: {integrity: sha512-tl}
    peerDependencies:
      react: ^18.0.0

  react@18.3.1:
    resolution: {integrity: sha512-react}
    engines: {node: '>=0.10.0'}

  undici@${undici}:
    resolution: {integrity: sha512-${undici}}

snapshots:

  '@testing-library/react@16.0.0(react@${peer})':
    dependencies:
      react: ${peer}

  react@18.3.1: {}

  undici@${undici}: {}
`;

describe("diffLockfile", () => {
  it("lists the packages whose Berry yarn.lock entries changed", () => {
    expect(diffLockfile("yarn.lock", yarnBerry("30.0.1"), yarnBerry("30.0.2"))).toEqual([
      "electron",
    ]);
  });

  it("ignores ranges that resolve to an entry that did not change", () => {
    const before = yarnBerry("30.0.1");
    const after = before.replace('"react@npm:^18.0.0":', '"react@npm:^18.0.0, react@npm:^18.3.0":');

    expect(diffLockfile("yarn.lock", before, after)).toEqual([]);
  });

  it("ignores workspace packages, whose source files the module graph traces", () => {
    const before = yarnBerry("30.0.1");
    const after = before.replace(
      'react: "npm:^18.0.0"',
      'react: "npm:^18.0.0"\n    clsx: "npm:^2.0.0"',
    );

    expect(diffLockfile("yarn.lock", before, after)).toEqual([]);
  });

  it("lists the packages whose v1 yarn.lock entries changed", () => {
    expect(diffLockfile("yarn.lock", yarnV1("18.2.0"), yarnV1("18.3.1"))).toEqual(["react"]);
  });

  it("lists the packages whose pnpm-lock.yaml entries changed", () => {
    expect(diffLockfile("apps/web/pnpm-lock.yaml", pnpmLock("6.19.0"), pnpmLock("6.19.8"))).toEqual(
      ["undici"],
    );
  });

  it("ignores pnpm entries that only change how packages link together", () => {
    expect(
      diffLockfile("pnpm-lock.yaml", pnpmLock("6.19.0"), pnpmLock("6.19.0", "18.3.2")),
    ).toEqual([]);
  });

  it("reads scoped packages from pnpm v6 keys", () => {
    const v6 = (version: string) => `lockfileVersion: '6.0'

packages:

  /@types/node@${version}:
    resolution: {integrity: sha512-${version}}
    dev: true

  /react-dom@18.3.1(react@18.3.1):
    resolution: {integrity: sha512-dom}
    dependencies:
      react: 18.3.1
`;

    expect(diffLockfile("pnpm-lock.yaml", v6("20.0.0"), v6("20.1.0"))).toEqual(["@types/node"]);
  });

  it("lists the packages whose package-lock.json entries changed", () => {
    const lock = (version: string) =>
      JSON.stringify({
        lockfileVersion: 3,
        packages: {
          "": { name: "root" },
          "packages/ui": { name: "@acme/ui", version: "1.0.0" },
          "node_modules/@acme/ui": { resolved: "packages/ui", link: true },
          "node_modules/react": { version: "18.3.1", integrity: "sha512-react" },
          "node_modules/a/node_modules/@types/node": { version, integrity: `sha512-${version}` },
        },
      });

    expect(diffLockfile("package-lock.json", lock("20.0.0"), lock("20.1.0"))).toEqual([
      "@types/node",
    ]);
  });

  it("treats every package as changed when the lockfile is added", () => {
    expect(diffLockfile("yarn.lock", undefined, yarnV1("18.3.1"))).toEqual([
      "@babel/runtime",
      "react",
    ]);
  });

  it("throws on a lockfile it cannot parse", () => {
    const conflicted = `${yarnV1("18.2.0")}<<<<<<< HEAD\n`;

    expect(() => diffLockfile("yarn.lock", yarnV1("18.2.0"), conflicted)).toThrow(
      'cannot read the package name in "<<<<<<< HEAD"',
    );
    expect(() => diffLockfile("package-lock.json", undefined, "{")).toThrow(SyntaxError);
  });

  it.each([
    ["yarn.lock", "__metadata:\n  version: 9\n"],
    ["pnpm-lock.yaml", "lockfileVersion: 5.4\n"],
    ["package-lock.json", "{}"],
  ])("throws on a %s version it does not know", (file, text) => {
    expect(() => diffLockfile(file, undefined, text)).toThrow("is not supported");
  });

  it.each([
    ["yarn.lock", true],
    ["apps/web/pnpm-lock.yaml", true],
    ["package-lock.json", true],
    ["bun.lock", false],
    ["bun.lockb", false],
  ])("knows whether %s is supported", (file, supported) => {
    expect(isSupportedLockfile(file)).toBe(supported);
  });
});

describe("readPackageNames", () => {
  it("reads plain, scoped, nested and pnpm node_modules paths", () => {
    expect(
      readPackageNames([
        "./src/Button.tsx",
        "./node_modules/react/index.js",
        "./../../node_modules/@radix-ui/react-dialog/dist/index.mjs",
        "./node_modules/a/node_modules/@scope/nested/index.js",
        "/repo/node_modules/.pnpm/clsx@2.1.1/node_modules/clsx/dist/clsx.mjs",
        "C:\\repo\\node_modules\\lodash\\lodash.js",
        "./node_modules/.cache/storybook-rsbuild-builder/storybook-stories.js",
      ]),
    ).toEqual(new Set(["react", "@radix-ui/react-dialog", "@scope/nested", "clsx", "lodash"]));
  });

  it("reads the loaders in a Webpack module name", () => {
    expect(
      readPackageNames([
        "./node_modules/style-loader/dist/index.js!./node_modules/css-loader/dist/cjs.js!./src/Button.css",
      ]),
    ).toEqual(new Set(["style-loader", "css-loader"]));
  });

  it("cannot tell when stats name no packages or only a cache of them", () => {
    expect(readPackageNames(["./src/Button.tsx"])).toBeUndefined();
    expect(
      readPackageNames(["./node_modules/react/index.js", "./node_modules/.vite/deps/react.js"]),
    ).toBeUndefined();
  });
});
